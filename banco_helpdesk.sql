drop table if exists historico;
drop table if exists chamados;

-- ---------- Tabelas ----------
create table chamados (
  n          bigint generated by default as identity primary key,
  titulo     text not null,
  nome       text not null,
  setor      text not null,
  email      text not null,
  tel        text not null,
  equip      text not null,
  num        text not null,
  cat        text not null,
  prio       text not null check (prio in ('baixa','media','alta','critica')),
  status     text not null default 'aberto' check (status in ('aberto','andamento','resolvido')),
  descricao  text not null,
  criado_em  timestamptz not null default now()
);

create table historico (
  id         bigint generated always as identity primary key,
  chamado_n  bigint not null references chamados(n) on delete cascade,
  autor      text not null,
  texto      text not null,
  quando     timestamptz not null default now()
);

-- ---------- Políticas de acesso (SOMENTE PARA PROTÓTIPO) ----------
-- Qualquer pessoa com a chave anon consegue ler e alterar.
-- Para uso real, trocar por Supabase Auth + políticas por perfil.
alter table chamados  enable row level security;
alter table historico enable row level security;
create policy "demo_chamados"  on chamados  for all using (true) with check (true);
create policy "demo_historico" on historico for all using (true) with check (true);

